// Note: standard ids must match `STANDARD_OPTIONS` ids in `src/lib/constants.ts`
export const STANDARD_CHECKLISTS: Record<string, ChecklistSection[]> = {
  ISO9001: ISO9001_SECTIONS,
  ISO14001: ISO14001_SECTIONS,
  GHP: GHP_SECTIONS,
  HACCP: HACCP_SECTIONS,
};

export function getChecklistQuestions(standardId: string): string[] {
  return STANDARD_CHECKLISTS[standardId]?.flatMap((section) => section.items) ?? [];
}

export function getChecklistSectionTitle(question: string): string | undefined {
  for (const sections of Object.values(STANDARD_CHECKLISTS)) {
    const match = sections.find((section) => section.items.includes(question));
    if (match) return match.title;
  }
  return undefined;
}

export function isTemplateQuestion(question: string): boolean {
  return Boolean(getChecklistSectionTitle(question));
}
